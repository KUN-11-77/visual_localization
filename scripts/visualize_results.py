import argparse
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

sns.set_style("seaborn-v0_8-paper")


def plot_recall_comparison(
    results_csv: str = "outputs/results/summary.csv",
    output_path: str = "outputs/visualizations/recall_comparison.png",
):
    """
    Grouped bar chart of recall at different thresholds.
    """
    df = pd.read_csv(results_csv)
    # Map evaluate.py output keys to our internal names
    threshold_keys = ["(0.25m, 2deg)", "(0.5m, 5deg)", "(5m, 10deg)"]
    threshold_labels = ["(0.25m, 2°)", "(0.5m, 5°)", "(5m, 10°)"]

    # Detect actual column names in CSV
    available_cols = df.columns.tolist()
    for key in threshold_keys:
        if key not in available_cols:
            raise KeyError(
                f"Column '{key}' not found in CSV. Available: {available_cols}\n"
                f"Please ensure the summary.csv was generated by run_pipeline.py"
            )

    experiments = df["experiment"].values
    x = np.arange(len(threshold_labels))
    width = 0.8 / len(experiments)

    fig, ax = plt.subplots(figsize=(10, 6))
    for i, exp in enumerate(experiments):
        vals = [df[df["experiment"] == exp][k].values[0] for k in threshold_keys]
        ax.bar(x + i * width, vals, width, label=exp)

    ax.set_xlabel("Threshold")
    ax.set_ylabel("Recall")
    ax.set_title("Localization Recall Comparison")
    ax.set_xticks(x + width * (len(experiments) - 1) / 2)
    ax.set_xticklabels(threshold_labels)
    ax.legend()
    ax.set_ylim(0, 1)
    plt.tight_layout()
    plt.savefig(output_path, dpi=300)
    print(f"Saved recall plot to {output_path}")


def visualize_keypoints(
    image: np.ndarray,
    keypoints: np.ndarray,
    scores: np.ndarray,
    output_path: str,
    max_kps: int = 1000,
):
    """
    Draw keypoints on image.
    Color encodes score: red=high, blue=low.
    """
    import cv2
    if len(keypoints) > max_kps:
        idx = np.argsort(scores)[::-1][:max_kps]
        keypoints = keypoints[idx]
        scores = scores[idx]

    vis = image.copy()
    norm_scores = (scores - scores.min()) / (scores.max() - scores.min() + 1e-8)

    for kp, s in zip(keypoints, norm_scores):
        color = int(255 * s)
        cv2.circle(vis, (int(kp[0]), int(kp[1])), 2, (color, 0, 255 - color), -1)

    cv2.imwrite(output_path, vis)
    print(f"Saved keypoints to {output_path}")


def visualize_matches(
    img_query: np.ndarray,
    img_db: np.ndarray,
    kpts_query: np.ndarray,
    kpts_db: np.ndarray,
    conf: np.ndarray,
    output_path: str,
    max_matches: int = 200,
):
    """
    Side-by-side image with match lines.
    """
    import cv2
    mask = conf > 0.5
    q_kpts = kpts_query[mask]
    db_kpts = kpts_db[mask]
    confs = conf[mask]

    if len(confs) > max_matches:
        idx = np.argsort(confs)[::-1][:max_matches]
        q_kpts = q_kpts[idx]
        db_kpts = db_kpts[idx]
        confs = confs[idx]

    h = max(img_query.shape[0], img_db.shape[0])
    w = img_query.shape[1] + img_db.shape[1] + 10
    canvas = np.zeros((h, w, 3), dtype=np.uint8)
    canvas[:img_query.shape[0], :img_query.shape[1]] = img_query
    canvas[:img_db.shape[0], img_query.shape[1] + 10:] = img_db

    offset = img_query.shape[1] + 10
    for q, d, c in zip(q_kpts, db_kpts, confs):
        color = (0, int(255 * c), int(255 * (1 - c)))
        q_int = (int(q[0]), int(q[1]))
        d_int = (int(d[0] + offset), int(d[1]))
        cv2.line(canvas, q_int, d_int, color, 1)
        cv2.circle(canvas, q_int, 2, (0, 255, 0), -1)
        cv2.circle(canvas, d_int, 2, (0, 255, 0), -1)

    cv2.imwrite(output_path, canvas)
    print(f"Saved matches to {output_path}")


def plot_timing_breakdown(
    timing_json: str = "outputs/results/timing.json",
    output_path: str = "outputs/visualizations/timing_breakdown.png",
):
    """
    Pie chart of mean time per stage.
    """
    import json
    with open(timing_json) as f:
        data = json.load(f)

    stages = list(data.keys())
    means = [data[s]["mean_ms"] for s in stages]
    total = sum(means)
    labels = [f"{s}\n{v:.1f}ms ({v/total*100:.0f}%)" for s, v in zip(stages, means)]

    fig, ax = plt.subplots(figsize=(8, 8))
    ax.pie(means, labels=labels, startangle=90)
    ax.set_title("Per-Module Timing Breakdown")
    plt.tight_layout()
    plt.savefig(output_path, dpi=300)
    print(f"Saved timing plot to {output_path}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", default="all", choices=["all", "recall", "timing"])
    args = parser.parse_args()

    if args.mode in ["all", "recall"]:
        plot_recall_comparison()
    if args.mode in ["all", "timing"]:
        plot_timing_breakdown()